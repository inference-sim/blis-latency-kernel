// The marked notes.

var marker = regexp.MustCompile(`KNOWN DIVERGENCE|KNOWN over-charge|COVERAGE LIMIT`)

type note struct {
	file, decl, heading, text string
	pos                       int
}

func divergences(root string) ([]byte, error) {
	var notes []note
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, path)
		if d.IsDir() {
			switch {
			case strings.HasPrefix(d.Name(), ".") && rel != ".", d.Name() == "testdata",
				d.Name() == "docs", rel == filepath.Join("internal", "docgen"):
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		found, err := notesIn(path, filepath.ToSlash(rel))
		notes = append(notes, found...)
		return err
	})
	if err != nil {
		return nil, err
	}
	sort.Slice(notes, func(i, j int) bool {
		if notes[i].file != notes[j].file {
			return notes[i].file < notes[j].file
		}
		return notes[i].pos < notes[j].pos
	})

	// Every note needs a summary, and every summary a note.
	used := map[string]bool{}
	for _, n := range notes {
		if used[n.key()] {
			return nil, fmt.Errorf("two %s notes in %s in %s; give one its own declaration "+
				"or extend the key", n.heading, n.decl, n.file)
		}
		used[n.key()] = true
		if _, ok := summaries[n.key()]; !ok {
			return nil, fmt.Errorf("the %s note in %s in %s has no summary; add %q to "+
				"internal/docgen/summaries.go", n.heading, n.decl, n.file, n.key())
		}
	}
	for key := range summaries {
		if !used[key] {
			return nil, fmt.Errorf("internal/docgen/summaries.go has a summary for %q, and "+
				"there is no such note", key)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "<!-- %s -->\n\n", generatedNote)
	// The kinds in use, defined once above the notes.
	var kinds []string
	for _, k := range noteKinds {
		for _, n := range notes {
			if n.heading == k.heading {
				kinds = append(kinds, k.heading)
				fmt.Fprintf(&b, "%s\n:   %s\n\n", k.heading, k.meaning)
				break
			}
		}
	}
	for _, n := range notes {
		s := summaries[n.key()]
		fmt.Fprintf(&b, "### %s\n\n", s.title)
		fmt.Fprintf(&b, "*%s, in `%s` in [`%s`](%s/blob/main/%s).*\n\n",
			n.heading, n.decl, n.file, repoURL, n.file)
		fmt.Fprintf(&b, "%s\n\n", s.summary)
		b.WriteString("??? quote \"The note in the source\"\n")
		for _, line := range strings.Split(n.text, "\n") {
			if line == "" {
				b.WriteString("\n")
				continue
			}
			fmt.Fprintf(&b, "    %s\n", markdownEscaper.Replace(line))
		}
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "*%d notes: %s.*\n", len(notes), countKinds(notes, kinds))
	return []byte(b.String()), nil
}

// noteKinds are the kinds of marked note, in the order the page defines them.
var noteKinds = []struct{ heading, meaning string }{
	{"Known divergence", "The engine does something the kernel prices differently on purpose."},
	{"Known over-charge", "A term the kernel knows is charged too high, kept because removing " +
		"it makes the measured accuracy worse. The note records the measurement."},
	{"Coverage limit", "Engine behavior the kernel does not model, with what it charges " +
		"instead."},
}

func countKinds(notes []note, kinds []string) string {
	var parts []string
	for _, k := range kinds {
		n := 0
		for _, x := range notes {
			if x.heading == k {
				n++
			}
		}
		parts = append(parts, fmt.Sprintf("%d %s", n, strings.ToLower(k)))
		if n != 1 {
			parts[len(parts)-1] += "s"
		}
	}
	return strings.Join(parts, ", ")
}

func (n note) key() string { return n.file + "|" + n.decl + "|" + n.heading }

// markdownEscaper keeps a source comment literal when it is quoted on a page: an identifier
// such as _quantize_and_setup_dispatch must not become emphasis, nor a bracket a link.
var markdownEscaper = strings.NewReplacer(`\`, `\\`, "*", `\*`, "_", `\_`, "`", "\\`",
	"[", `\[`, "]", `\]`, "<", "&lt;", ">", "&gt;")

// notesIn returns the marked paragraphs of one file, each with the declaration it is in.
func notesIn(path, rel string) ([]note, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var out []note
	for _, cg := range f.Comments {
		text := cg.Text()
		for _, para := range strings.Split(text, "\n\n") {
			loc := marker.FindStringIndex(para)
			// A mention that points back to a note ("the KNOWN over-charge above") is not
			// itself one.
			if loc == nil || strings.HasSuffix(strings.TrimSpace(para[:loc[0]]), "the") {
				continue
			}
			heading := "Coverage limit"
			if m := para[loc[0]:loc[1]]; strings.HasPrefix(m, "KNOWN") {
				heading = "Known over-charge"
				if m == "KNOWN DIVERGENCE" {
					heading = "Known divergence"
				}
			}
			out = append(out, note{
				file: rel, decl: enclosing(f, cg.Pos()), heading: heading,
				text: strings.TrimRight(para, "\n"), pos: int(cg.Pos()),
			})
		}
	}
	return out, nil
}

// enclosing names the declaration a comment documents or sits inside.
func enclosing(f *ast.File, pos token.Pos) string {
	for _, d := range f.Decls {
		var docStart token.Pos = d.Pos()
		switch d := d.(type) {
		case *ast.FuncDecl:
			if d.Doc != nil {
				docStart = d.Doc.Pos()
			}
			if pos >= docStart && pos <= d.End() {
				if d.Recv != nil && len(d.Recv.List) > 0 {
					return fmt.Sprintf("(%s).%s", exprString(d.Recv.List[0].Type), d.Name.Name)
				}
				return d.Name.Name
			}
		case *ast.GenDecl:
			if d.Doc != nil {
				docStart = d.Doc.Pos()
			}
			if pos >= docStart && pos <= d.End() {
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.ValueSpec:
						return s.Names[0].Name
					case *ast.TypeSpec:
						return s.Name.Name
					}
				}
			}
		}
	}
	return "package " + f.Name.Name
}

func exprString(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.StarExpr:
		return "*" + exprString(e.X)
	case *ast.Ident:
		return e.Name
	}
	return "?"
}

