// Command docgen writes the generated parts of the documentation into docs/generated/:
//
//	step-anatomy.html  the figure on "Pricing a step", computed by this kernel
//	divergences.md     every note in the source headed KNOWN DIVERGENCE, KNOWN over-charge
//	                   or COVERAGE LIMIT, with where it is
//	sources.md         the versions and commits the kernel's behavior and inputs are pinned to
//
// Run it after changing the cost model, a marked note, or a pin, and commit what it writes:
//
//	go run ./internal/docgen
//
// TestGeneratedDocsAreCurrent fails while a committed file differs from what this would write.
// It needs the fetched catalog and registry (scripts/fetch-testdata.sh), because the figure is
// priced from them.
package main

